//! The static `/etc` tree of a generation.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs::{self, DirBuilder, OpenOptions};
use std::io::Write as _;
use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt, PermissionsExt, fchown, symlink};
use std::path::{Path, PathBuf};

use laft_core::{system_gid, system_uid};
use laft_store::{EtcRecord, Store};
use serde_json::Value;

use crate::accounts::DATABASES;
use crate::config::{EtcConfig, File};
use crate::error::{ConfigError, Error, Result, Warning, io};
use crate::{Declared, format, fsx};

/// The first line of every file Laft generates from kernel settings.
const HEADER: &str = "# Generated by laft.\n";

/// One entry of the static `/etc` tree.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Node {
    /// A directory.
    Dir,
    /// A file with this content, mode and owner.
    File {
        /// The content.
        bytes: Vec<u8>,
        /// The permission bits.
        mode: u32,
        /// The owning uid.
        uid: u32,
        /// The owning gid.
        gid: u32,
    },
    /// A file a package ships, hard linked from its store entry.
    Linked(PathBuf),
    /// A symlink with this target.
    Symlink(String),
}

/// The rendered static `/etc` tree of a generation.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct EtcTree {
    nodes: BTreeMap<String, Node>,
    copy: BTreeSet<String>,
    warnings: Vec<Warning>,
}

/// Renders the static `/etc` tree of a generation.
///
/// The tree is built from three sources, and a later one replaces an
/// earlier one at the same path:
///
/// 1. The `etc/` entries of the packages `packages`, given as store entry
///    directory names. Two packages shipping the same path are an error.
/// 2. Files derived from the configuration: `hostname`, `hosts`,
///    `localtime`, `timezone`, `locale.conf`, `profile.d/locale.sh`,
///    `vconsole.conf` when a keymap or console font is set,
///    `ssh/authorized_keys.d/<user>` for users with SSH keys, and
///    `modules-load.d/laft.conf`, `modprobe.d/laft.conf` and
///    `sysctl.d/laft.conf`. Next to them, `generated` holds the entries
///    other subsystems render, such as the init system's entry points, by
///    path relative to `/etc`.
/// 3. The declared files that are enabled.
///
/// Finally every declared file that is disabled removes its path. Owners of
/// declared files resolve against `declared`, then against the static
/// system accounts.
///
/// ```no_run
/// use laft_activate::{EtcConfig, declare, render};
/// use laft_store::Root;
///
/// let root = Root::new("/mnt");
/// let lock = root.lock("apply")?;
/// let config = EtcConfig::default();
/// let declared = declare(&lock, &config.users)?;
/// let tree = render(&config, &declared, &root.store(), &[], &Default::default())?;
/// tree.write("/mnt/laft/tmp/gen-7".as_ref())?;
/// declared.write("/mnt/laft/tmp/gen-7".as_ref())?;
/// # Ok::<(), laft_activate::Error>(())
/// ```
///
/// # Errors
///
/// Fails with [`Error::Config`] listing every invalid file, kernel setting
/// and sysctl, with [`Error::PackageConflict`] when two packages ship the
/// same path, with [`Error::Invalid`] when a generated entry has the path
/// of a derived file, and when a package manifest or a `source` file cannot
/// be read.
pub fn render(
    config: &EtcConfig,
    declared: &Declared,
    store: &Store,
    packages: &[String],
    generated: &BTreeMap<String, Node>,
) -> Result<EtcTree> {
    let mut tree = EtcTree::default();
    package_defaults(store, packages, &mut tree.nodes)?;
    let mut errors = Vec::new();
    let derived = derived(config, &mut errors);
    if let Some((path, _)) = derived
        .iter()
        .find(|(path, _)| generated.contains_key(path))
    {
        return Err(Error::Invalid(format!(
            "/etc/{path} is both derived from the configuration and generated by another subsystem"
        )));
    }
    let generated = generated
        .iter()
        .map(|(path, node)| (path.clone(), node.clone()));
    for (path, node) in derived.into_iter().chain(generated) {
        place(&mut tree.nodes, &path, node, &mut errors);
    }
    let mut disabled = Vec::new();
    for (label, file) in &config.files {
        let Some(path) = check_label(label, &mut errors) else {
            continue;
        };
        if !file.enable {
            disabled.push(path);
            continue;
        }
        let Some(node) = file_node(label, file, declared, &mut errors)? else {
            continue;
        };
        if file.copy {
            tree.copy.insert(path.to_owned());
        }
        if file.link.is_none() && file.mode & 0o004 == 0 {
            tree.warnings.push(Warning::PrivateFile {
                path: label.clone(),
                mode: file.mode,
            });
        }
        place(&mut tree.nodes, path, node, &mut errors);
    }
    for path in disabled {
        let below = format!("{path}/");
        tree.nodes
            .retain(|p, _| p != path && !p.starts_with(&below));
        tree.copy.remove(path);
    }
    if !errors.is_empty() {
        return Err(Error::Config(errors));
    }
    Ok(tree)
}

impl EtcTree {
    /// Every entry, by path relative to `/etc`.
    pub fn entries(&self) -> &BTreeMap<String, Node> {
        &self.nodes
    }

    /// Things the user should know about the declared files.
    pub fn warnings(&self) -> &[Warning] {
        &self.warnings
    }

    /// The paths `/etc` links into the static tree, and the paths it
    /// copies, which include the account databases.
    pub fn record(&self) -> EtcRecord {
        let mut copy = self.copy.clone();
        copy.extend(DATABASES.iter().map(|&db| db.to_owned()));
        EtcRecord {
            managed: self
                .nodes
                .iter()
                .filter(|(path, node)| **node != Node::Dir && !copy.contains(*path))
                .map(|(path, _)| path.clone())
                .collect(),
            copy: copy.into_iter().collect(),
        }
    }

    /// Writes the tree as `etc` below `generation_dir`, a generation tree
    /// under construction. Directories get mode `0o755`, and package files
    /// are hard links to their store files.
    ///
    /// Files are not synced one by one, because a generation is published
    /// with one rename after its whole tree is synced. Owners are set only
    /// when running as root.
    ///
    /// # Errors
    ///
    /// Fails when an entry exists already or cannot be written.
    pub fn write(&self, generation_dir: &Path) -> Result<()> {
        let etc = generation_dir.join("etc");
        create_dir(&etc)?;
        for (relative, node) in &self.nodes {
            let path = etc.join(relative);
            let parent = fsx::parent(&path);
            if !parent.exists() {
                fs::create_dir_all(parent).map_err(io(parent))?;
            }
            match node {
                Node::Dir => create_dir(&path)?,
                Node::File {
                    bytes,
                    mode,
                    uid,
                    gid,
                } => {
                    let mut file = OpenOptions::new()
                        .write(true)
                        .create_new(true)
                        .mode(0o600)
                        .open(&path)
                        .map_err(io(&path))?;
                    file.write_all(bytes).map_err(io(&path))?;
                    if fsx::is_root() {
                        fchown(&file, Some(*uid), Some(*gid)).map_err(io(&path))?;
                    }
                    file.set_permissions(fs::Permissions::from_mode(*mode))
                        .map_err(io(&path))?;
                }
                Node::Linked(source) => fs::hard_link(source, &path).map_err(io(&path))?,
                Node::Symlink(target) => symlink(target, &path).map_err(io(&path))?,
            }
        }
        Ok(())
    }
}

/// Creates directory `path` with mode `0o755` unless it exists.
fn create_dir(path: &Path) -> Result<()> {
    if fsx::lstat(path)?.is_some_and(|m| m.is_dir()) {
        return Ok(());
    }
    DirBuilder::new()
        .mode(0o755)
        .recursive(true)
        .create(path)
        .map_err(io(path))?;
    fs::set_permissions(path, fs::Permissions::from_mode(0o755)).map_err(io(path))
}

/// Adds the `etc/` entries of every package.
fn package_defaults(
    store: &Store,
    packages: &[String],
    nodes: &mut BTreeMap<String, Node>,
) -> Result<()> {
    let mut owners: BTreeMap<String, String> = BTreeMap::new();
    for dir in packages {
        let manifest = store.manifest(dir)?;
        let package = manifest.package();
        let label = format!("{} {}-r{}", package.name, package.version, package.rev);
        let entry_dir = store.path(dir);
        for entry in manifest.entries() {
            let Some(relative) = entry.path().strip_prefix("etc/") else {
                continue;
            };
            let node = match entry {
                laft_pkg::Entry::Dir { .. } => Node::Dir,
                laft_pkg::Entry::File { path, .. } => Node::Linked(entry_dir.join(path)),
                laft_pkg::Entry::Symlink { target, .. } => Node::Symlink(target.clone()),
            };
            match (nodes.get(relative), owners.get(relative)) {
                (Some(Node::Dir), _) if node == Node::Dir => continue,
                (Some(_), Some(owner)) => {
                    return Err(Error::PackageConflict {
                        path: relative.to_owned(),
                        owners: [owner.clone(), label],
                    });
                }
                _ => {}
            }
            owners.insert(relative.to_owned(), label.clone());
            nodes.insert(relative.to_owned(), node);
        }
    }
    Ok(())
}

/// Puts `node` at `path`, replacing what is there, and creates missing
/// parent directories. A parent that is not a directory, or a directory
/// with entries that a file would replace, is a clash.
fn place(
    nodes: &mut BTreeMap<String, Node>,
    path: &str,
    node: Node,
    errors: &mut Vec<ConfigError>,
) {
    let clash = |file: &str| ConfigError::PathClash {
        path: format!("/etc/{path}"),
        file: format!("/etc/{file}"),
    };
    let mut parents = Vec::new();
    let mut rest = path;
    while let Some((parent, _)) = rest.rsplit_once('/') {
        parents.push(parent);
        rest = parent;
    }
    for parent in parents.into_iter().rev() {
        match nodes.get(parent) {
            None => {
                nodes.insert(parent.to_owned(), Node::Dir);
            }
            Some(Node::Dir) => {}
            Some(_) => {
                errors.push(clash(parent));
                return;
            }
        }
    }
    if node != Node::Dir && nodes.get(path) == Some(&Node::Dir) {
        let below = format!("{path}/");
        if let Some((child, _)) = nodes.range(below.clone()..).next()
            && child.starts_with(&below)
        {
            errors.push(ConfigError::PathClash {
                path: format!("/etc/{child}"),
                file: format!("/etc/{path}"),
            });
            return;
        }
    }
    nodes.insert(path.to_owned(), node);
}

/// A plain root-owned file with mode `0o644`.
fn text(content: String) -> Node {
    Node::File {
        bytes: content.into_bytes(),
        mode: 0o644,
        uid: 0,
        gid: 0,
    }
}

/// The files derived from typed configuration.
fn derived(config: &EtcConfig, errors: &mut Vec<ConfigError>) -> Vec<(String, Node)> {
    let hostname = &config.hostname;
    let mut files = vec![
        ("hostname".to_owned(), text(format!("{hostname}\n"))),
        (
            "hosts".to_owned(),
            text(format!(
                "127.0.0.1 localhost\n::1 localhost\n127.0.1.1 {hostname}\n"
            )),
        ),
        (
            "localtime".to_owned(),
            Node::Symlink(format!("/usr/share/zoneinfo/{}", config.timezone)),
        ),
        (
            "timezone".to_owned(),
            text(format!("{}\n", config.timezone)),
        ),
        (
            "locale.conf".to_owned(),
            text(format!("LANG={}\n", config.locale)),
        ),
        (
            "profile.d/locale.sh".to_owned(),
            text(format!(
                "export LANG={}\n",
                format::env_value(&config.locale)
            )),
        ),
    ];
    if config.keymap.is_some() || config.console_font.is_some() {
        let mut vconsole = String::new();
        if let Some(keymap) = &config.keymap {
            let _ = writeln!(vconsole, "KEYMAP={keymap}");
        }
        if let Some(font) = &config.console_font {
            let _ = writeln!(vconsole, "FONT={font}");
        }
        files.push(("vconsole.conf".to_owned(), text(vconsole)));
    }
    for (name, user) in &config.users.accounts {
        if user.ssh_keys.is_empty() {
            continue;
        }
        if user.ssh_keys.iter().any(|k| k.contains(['\n', '\r'])) {
            errors.push(ConfigError::InvalidValue {
                context: format!("user {name:?}: ssh_keys"),
                reason: "a key cannot contain a line break",
            });
        }
        let keys: String = user.ssh_keys.iter().map(|k| format!("{k}\n")).collect();
        files.push((format!("ssh/authorized_keys.d/{name}"), text(keys)));
    }
    files.extend(kernel_files(config, errors));
    files
}

/// `modules-load.d/laft.conf`, `modprobe.d/laft.conf` and
/// `sysctl.d/laft.conf`.
fn kernel_files(config: &EtcConfig, errors: &mut Vec<ConfigError>) -> Vec<(String, Node)> {
    let kernel = &config.kernel;
    let module_name = |m: &str| {
        !m.is_empty()
            && m.chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    };
    let names = kernel
        .modules
        .iter()
        .chain(&kernel.blacklist)
        .chain(kernel.options.keys());
    for module in names {
        if !module_name(module) {
            errors.push(ConfigError::InvalidValue {
                context: format!("kernel module {module:?}"),
                reason: "a module name holds only A-Z, a-z, 0-9, `_` and `-`",
            });
        }
    }
    for module in &kernel.modules {
        if kernel.blacklist.contains(module) {
            errors.push(ConfigError::BlacklistedModule(module.clone()));
        }
    }

    let mut load = HEADER.to_owned();
    for module in &kernel.modules {
        let _ = writeln!(load, "{module}");
    }
    let mut modprobe = HEADER.to_owned();
    for module in &kernel.blacklist {
        let _ = writeln!(modprobe, "blacklist {module}");
    }
    for (module, options) in &kernel.options {
        if options.contains(['\n', '\r']) {
            errors.push(ConfigError::InvalidValue {
                context: format!("kernel options of {module:?}"),
                reason: "options cannot contain a line break",
            });
        }
        let _ = writeln!(modprobe, "options {module} {options}");
    }
    let mut sysctl = HEADER.to_owned();
    for (key, value) in &config.sysctl {
        if !valid_sysctl_key(key) {
            errors.push(ConfigError::SysctlKey(key.clone()));
        }
        let value = match value {
            Value::Bool(b) => u8::from(*b).to_string(),
            Value::Number(n) if n.is_i64() || n.is_u64() => n.to_string(),
            Value::String(s) if !s.contains(['\n', '\r']) => s.clone(),
            _ => {
                errors.push(ConfigError::SysctlValue(key.clone()));
                continue;
            }
        };
        let _ = writeln!(sysctl, "{key} = {value}");
    }
    vec![
        ("modules-load.d/laft.conf".to_owned(), text(load)),
        ("modprobe.d/laft.conf".to_owned(), text(modprobe)),
        ("sysctl.d/laft.conf".to_owned(), text(sysctl)),
    ]
}

/// Whether `key` matches `[a-z0-9_.-]+(/[a-z0-9_.-]+)*` without `..`.
fn valid_sysctl_key(key: &str) -> bool {
    !key.contains("..")
        && key.split('/').all(|part| {
            !part.is_empty()
                && part
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || "_.-".contains(c))
        })
}

/// The path of the declared file `label` relative to `/etc`, or `None`
/// after recording why the label is invalid.
fn check_label<'a>(label: &'a str, errors: &mut Vec<ConfigError>) -> Option<&'a str> {
    let normalized = label.strip_prefix("/etc/").filter(|rest| {
        !rest.contains('\0')
            && rest
                .split('/')
                .all(|part| !part.is_empty() && part != "." && part != "..")
    });
    let Some(path) = normalized else {
        errors.push(ConfigError::InvalidPath(label.to_owned()));
        return None;
    };
    let top = path.split('/').next().unwrap_or(path);
    if top == "static" || top == "laft" || DATABASES.contains(&path) {
        errors.push(ConfigError::ReservedPath(label.to_owned()));
        return None;
    }
    Some(path)
}

/// The node of an enabled declared file, or `None` after recording why it
/// is invalid.
fn file_node(
    label: &str,
    file: &File,
    declared: &Declared,
    errors: &mut Vec<ConfigError>,
) -> Result<Option<Node>> {
    let contents = [
        file.text.is_some(),
        file.source.is_some(),
        file.link.is_some(),
        file.json.is_some(),
        file.toml.is_some(),
        file.yaml.is_some(),
        file.ini.is_some(),
        file.env.is_some(),
    ];
    if contents.iter().filter(|&&set| set).count() != 1 {
        errors.push(ConfigError::Content(label.to_owned()));
        return Ok(None);
    }
    let invalid = |reason| ConfigError::InvalidValue {
        context: format!("file {label:?}"),
        reason,
    };
    if let Some(target) = &file.link {
        if file.copy {
            errors.push(invalid("a link cannot be copied"));
            return Ok(None);
        }
        if target.is_empty() {
            errors.push(invalid("a link target cannot be empty"));
            return Ok(None);
        }
        return Ok(Some(Node::Symlink(target.clone())));
    }
    if file.mode > 0o777 {
        errors.push(invalid(
            "the mode may only hold permission bits up to 0o777",
        ));
        return Ok(None);
    }
    let structure = |reason: String| ConfigError::Structure {
        path: label.to_owned(),
        reason,
    };
    let rendered = if let Some(text) = &file.text {
        Ok(text.clone().into_bytes())
    } else if let Some(source) = &file.source {
        Ok(fs::read(source).map_err(io(source))?)
    } else if let Some(value) = &file.json {
        format::json(value)
            .map(String::into_bytes)
            .map_err(structure)
    } else if let Some(value) = &file.toml {
        format::toml::render(value)
            .map(String::into_bytes)
            .map_err(structure)
    } else if let Some(value) = &file.yaml {
        Ok(format::yaml::render(value).into_bytes())
    } else if let Some(sections) = &file.ini {
        format::ini(sections)
            .map(String::into_bytes)
            .map_err(structure)
    } else if let Some(vars) = &file.env {
        format::env(vars)
            .map(String::into_bytes)
            .map_err(|key| ConfigError::EnvKey {
                path: label.to_owned(),
                key,
            })
    } else {
        Err(ConfigError::Content(label.to_owned()))
    };
    let uid = declared
        .users
        .get(&file.owner)
        .map(|u| u.uid)
        .or_else(|| system_uid(&file.owner));
    let gid = declared
        .groups
        .get(&file.group)
        .map(|g| g.gid)
        .or_else(|| system_gid(&file.group));
    let mut unknown = |kind, name: &str| {
        errors.push(ConfigError::UnknownAccount {
            kind,
            name: name.to_owned(),
            context: format!("file {label:?}"),
        });
    };
    if uid.is_none() {
        unknown("user", &file.owner);
    }
    if gid.is_none() {
        unknown("group", &file.group);
    }
    match (rendered, uid, gid) {
        (Ok(bytes), Some(uid), Some(gid)) => Ok(Some(Node::File {
            bytes,
            mode: file.mode,
            uid,
            gid,
        })),
        (Err(error), _, _) => {
            errors.push(error);
            Ok(None)
        }
        _ => Ok(None),
    }
}

