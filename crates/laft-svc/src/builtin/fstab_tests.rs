use super::*;

#[test]
fn fstab_lines_are_read_with_their_escapes_and_defaults() {
    let text = "# Generated by laft.\n\n\
        UUID=1 / ext4 rw,relatime 0 1\n\
        /dev/sda2 /srv/my\\040data xfs defaults 0 2\n\
        tmpfs /tmp tmpfs\n\
        UUID=5 none swap pri=10 0 0\n";
    let entries = parse_fstab(text).unwrap();
    assert_eq!(entries.len(), 4);
    assert_eq!(entries[0].pass, 1);
    assert_eq!(entries[1].mountpoint, "/srv/my data");
    assert_eq!(entries[2].options, "defaults");
    assert_eq!(entries[2].pass, 0);
    assert!(entries[3].is_swap() && !entries[0].is_swap());
}

#[test]
fn malformed_fstab_lines_are_reported_by_number() {
    assert_eq!(parse_fstab("\n/dev/sda1 /\n").unwrap_err().0, 2);
    assert_eq!(parse_fstab("/dev/sda1 / ext4 rw 0 x\n").unwrap_err().0, 1);
}

#[test]
fn escapes_round_trip_and_out_of_range_ones_stay() {
    for text in ["/a b", "/tab\there", "/back\\slash", "/plain"] {
        assert_eq!(unescape(&escape(text)), text);
    }
    assert_eq!(unescape("\\777"), "\\777");
    assert_eq!(unescape("\\04"), "\\04");
}

#[test]
fn mountinfo_lists_decoded_mountpoints() {
    let info = "22 1 0:21 / /proc rw,nosuid shared:5 - proc proc rw\n\
        30 22 0:30 / /mnt/a\\040b rw - ext4 /dev/sdb1 rw\n";
    let points = mountpoints(info);
    assert!(points.contains("/proc"));
    assert!(points.contains("/mnt/a b"));
}
