//! The commands that only read, run against an applied root.

mod support;

use std::fs;

use support::pkg;

fn hello() -> support::Pkg {
    pkg("hello", "1.0")
        .file("usr/bin/hello", b"#!/bin/sh\necho hello\n")
        .file("etc/hello.conf", b"greeting = hello\n")
}

#[test]
fn package_questions_are_answered_from_the_indexes_and_the_generation() {
    let fx = fixture!(
        hello(),
        pkg("hello-docs", "1.0").file("usr/share/doc/hello", b"docs")
    );
    fx.configure(", hello", "  file \"/etc/motd\" { text = \"hi\\n\" }");
    fx.laft(&["apply", "-y"]).expect(0);

    let search = fx.laft(&["search", "hel"]).expect(0);
    let rows: Vec<&str> = search.stdout.lines().collect();
    assert!(rows[0].starts_with("hello "), "{}", search.stdout);
    assert!(
        rows[0].contains("[installed: dynamic]"),
        "{}",
        search.stdout
    );
    assert!(rows[1].starts_with("hello-docs "), "{}", search.stdout);
    let json = fx.laft(&["search", "--json", "docs"]).expect(0).json();
    assert_eq!(json["results"][0]["name"], "hello-docs");

    let info = fx.laft(&["info", "hello"]).expect(0);
    assert!(
        info.stdout.contains("version      1.0-r1"),
        "{}",
        info.stdout
    );
    let info = fx.laft(&["info", "--json", "hello"]).expect(0).json();
    assert_eq!(info["installed_in"], serde_json::json!(["system"]));
    fx.laft(&["info", "nothing-here"]).expect(1);

    let files = fx.laft(&["files", "hello"]).expect(0);
    assert!(
        files.stdout.lines().any(|l| l == "/usr/bin/hello"),
        "{}",
        files.stdout
    );
    let cached = |fx: &support::Fixture| {
        std::fs::read_dir(fx.root().join("laft/cache/pkgs"))
            .map(|d| d.count())
            .unwrap_or(0)
    };
    let before = cached(&fx);
    let docs = fx.laft(&["files", "-l", "hello-docs"]).expect(0);
    assert_eq!(cached(&fx), before, "laft files leaves the cache alone");
    assert!(
        docs.stdout
            .contains("file  0444  root:root  4  /usr/share/doc/hello"),
        "{}",
        docs.stdout
    );

    let owns = fx.laft(&["owns", "hello"]).expect(0);
    assert_eq!(
        owns.stdout.trim(),
        "/usr/bin/hello is owned by hello 1.0-r1 (dynamic)"
    );
    let owns = fx.laft(&["owns", "/etc/hello.conf"]).expect(0);
    assert_eq!(
        owns.stdout.trim(),
        "/etc/hello.conf is managed, the default of hello"
    );
    let owns = fx.laft(&["owns", "/etc/motd"]).expect(0);
    assert!(
        owns.stdout.contains("from file \"/etc/motd\" at "),
        "{}",
        owns.stdout
    );
    assert!(owns.stdout.contains("system.stav:"), "{}", owns.stdout);
    let owns = fx
        .laft(&["owns", "/usr/lib/modules/6.1.0-laft1/modules.dep"])
        .expect(0);
    assert!(
        owns.stdout.contains("generated by trigger depmod"),
        "{}",
        owns.stdout
    );

    let why = fx.laft(&["why", "linux"]).expect(0);
    assert!(
        why.stdout.contains("is in view \"system\" because:"),
        "{}",
        why.stdout
    );
    assert!(
        why.stdout.contains("requested at boot.kernel (linux)"),
        "{}",
        why.stdout
    );
    let why = fx.laft(&["why", "hello"]).expect(0);
    assert!(
        why.stdout
            .contains("requested at /etc/laft/system.stav:3:43 (hello)"),
        "{}",
        why.stdout
    );
}

#[test]
fn repositories_generations_and_etc_can_be_inspected() {
    let fx = fixture!(hello());
    fx.configure(", hello", "");
    fx.laft(&["apply", "-y"]).expect(0);
    fx.configure("", "");
    fx.laft(&["apply", "-y"]).expect(0);

    let list = fx.laft(&["repo", "list"]).expect(0);
    assert!(
        list.stdout
            .lines()
            .nth(1)
            .is_some_and(|l| l.starts_with("core  current")),
        "{}",
        list.stdout
    );
    assert!(list.stdout.contains(" ok"), "{}", list.stdout);
    fx.laft(&["repo", "sync"]).expect(0);
    fx.laft(&["repo", "sync", "other"]).expect(2);

    let diff = fx.laft(&["gens", "diff", "1"]).expect(0);
    assert!(diff.stdout.contains("- hello"), "{}", diff.stdout);
    assert!(diff.stdout.contains("- hello.conf"), "{}", diff.stdout);
    let json = fx
        .laft(&["gens", "diff", "--json", "1", "2"])
        .expect(0)
        .json();
    assert_eq!(json["packages"]["system"]["removed"][0]["name"], "hello");

    std::fs::remove_file(fx.root().join("etc/hostname")).expect("managed");
    std::fs::write(fx.root().join("etc/hostname"), "elsewhere\n").expect("writable");
    let status = fx.laft(&["etc", "status"]).expect(0);
    assert!(
        status
            .stdout
            .contains("/etc/hostname  replaced by the user"),
        "{}",
        status.stdout
    );
    let diff = fx.laft(&["etc", "diff", "/etc/hostname"]).expect(0);
    assert!(
        diff.stdout.contains("-elsewhere\n+forge"),
        "{}",
        diff.stdout
    );
    fx.laft(&["etc", "reset", "-y", "hostname"]).expect(0);
    assert_eq!(fx.etc("hostname"), "forge\n");
    assert_eq!(fx.read("etc/hostname.laft-old"), "elsewhere\n");

    fx.laft(&["gens", "rm", "-y", "2"]).expect(2);
    fx.laft(&["gens", "rm", "-y", "1"]).expect(0);
    assert!(!fx.root().join("laft/gens/1").exists());

    fx.laft(&["verify"]).expect(0);
    let doctor = fx.laft(&["doctor"]).expect(9);
    assert!(doctor.stdout.contains("layout"), "{}", doctor.stdout);
    assert!(doctor.stdout.contains("journal"), "{}", doctor.stdout);
}

#[test]
fn gens_show_prints_the_option_values_of_each_package() {
    let mesa = pkg("mesa", "1.0")
        .file("usr/bin/mesa", b"m")
        .option("x11", laft_core::OptionValue::Bool(false));
    let fx = fixture!(hello());
    fx.publish_with_recipes(vec![mesa], Some(&mesa_recipes(fx.dir())));
    fx.configure(", mesa", "");
    fx.laft(&["apply", "-y"]).expect(0);

    let show = fx.laft(&["gens", "show", "1", "--packages"]).expect(0);
    assert!(show.stdout.contains("x11=false"), "{}", show.stdout);
    let json = fx
        .laft(&["gens", "show", "--json", "1", "--packages"])
        .expect(0)
        .json();
    let mesa = json["packages"]
        .as_array()
        .expect("packages")
        .iter()
        .find(|p| p["name"] == "mesa")
        .expect("mesa is in the generation");
    assert_eq!(mesa["options"]["x11"], false);
}

/// `laft why` shows the option values that differ from their preferred
/// values, with the fixed setting that overrode the preference.
#[test]
fn why_names_the_option_values_that_moved_off_the_preference() {
    let mesa = pkg("mesa", "1.0")
        .file("usr/bin/mesa", b"m")
        .option("x11", laft_core::OptionValue::Bool(false));
    let fx = fixture!(hello());
    fx.publish_with_recipes(vec![mesa], Some(&mesa_recipes(fx.dir())));
    fx.configure(", mesa", "");
    fx.laft(&["repo", "sync"]).expect(0);
    fx.configure(", mesa", "  package.mesa.x11 = false\n");
    fx.laft(&["apply", "-y"]).expect(0);

    let why = fx.laft(&["why", "mesa"]).expect(0);
    assert!(
        why.stdout.contains("mesa 1.0-r1 (x11=false)"),
        "{}",
        why.stdout
    );
    assert!(
        why.stdout
            .contains("x11=false      set at /etc/laft/system.stav:"),
        "{}",
        why.stdout
    );
    let json = fx.laft(&["why", "--json", "mesa"]).expect(0).json();
    assert_eq!(json["why"][0]["options"]["x11"], false);
    assert_eq!(json["why"][0]["reasons"][0]["kind"], "requested");
    assert_eq!(json["why"][0]["reasons"][1]["kind"], "option_moved");
    assert_eq!(json["why"][0]["reasons"][1]["option"], "x11");
    assert_eq!(json["why"][0]["reasons"][1]["chosen"], false);
    assert_eq!(json["why"][0]["reasons"][1]["preferred"], true);
}

/// `laft info` shows the option declarations of the recipe and the
/// option sets that are published.
#[test]
fn info_shows_the_option_declarations_and_the_published_sets() {
    let mesa = |version: &str, x11: bool| {
        pkg("mesa", version)
            .file("usr/bin/mesa", b"m")
            .option("x11", laft_core::OptionValue::Bool(x11))
    };
    let fx = fixture!(hello());
    fx.publish_with_recipes(
        vec![mesa("1.0", false), mesa("1.1", true)],
        Some(&mesa_recipes(fx.dir())),
    );
    fx.configure(", mesa", "");
    fx.laft(&["repo", "sync"]).expect(0);

    let info = fx.laft(&["info", "mesa"]).expect(0);
    assert!(
        info.stdout
            .contains("options      x11 (bool, default true) Build against X11."),
        "{}",
        info.stdout
    );
    assert!(
        info.stdout.contains("published    x11=false at 1.0-r1"),
        "{}",
        info.stdout
    );
    assert!(
        info.stdout.contains("published    x11=true at 1.1-r1"),
        "{}",
        info.stdout
    );
    let info = fx.laft(&["info", "--json", "mesa"]).expect(0).json();
    assert_eq!(info["options"][0]["name"], "x11");
    assert_eq!(info["published"][0]["values"]["x11"], "false");
    assert_eq!(
        info["published"][0]["entries"],
        serde_json::json!(["1.0-r1"])
    );
}

/// The recipe sources of a `mesa` package that declares one option.
fn mesa_recipes(dir: &std::path::Path) -> std::path::PathBuf {
    let recipes = dir.join("recipes-src");
    fs::create_dir_all(recipes.join("recipes/mesa")).expect("writable");
    fs::write(recipes.join("recipes.stav"), "recipe_repo core {}\n").expect("writable");
    fs::write(
        recipes.join("recipes/mesa/package.stav"),
        "package mesa {\n  version = \"1.0\"\n  summary = \"Mesa\"\n  license = [MIT]\n  empty = true\n  build custom {}\n}\n",
    )
    .expect("writable");
    fs::write(
        recipes.join("recipes/mesa/options.stav"),
        "## The X11 support.\nstruct Options {\n  ## Build against X11.\n  x11: Bool = true\n}\n",
    )
    .expect("writable");
    recipes
}

#[test]
fn the_configuration_tools_format_check_and_print_it() {
    let fx = fixture!(hello());
    fx.configure(", hello", "");
    let config = fx.root().join("etc/laft/system.stav");
    let ugly = std::fs::read_to_string(&config)
        .expect("written")
        .replace("  hostname", "hostname");
    std::fs::write(&config, &ugly).expect("writable");
    fx.laft(&["fmt", "--check"]).expect(1);
    fx.laft(&["fmt"]).expect(0);
    fx.laft(&["fmt", "--check"]).expect(0);
    fx.laft(&["check"]).expect(5);
    fx.laft(&["repo", "sync"]).expect(0);
    fx.laft(&["check"]).expect(0);

    let eval = fx.laft(&["eval", "hostname"]).expect(0);
    assert_eq!(eval.stdout.trim(), "\"forge\"");
    let toml = fx.laft(&["eval", "gc", "-o", "toml"]).expect(0);
    assert!(
        toml.stdout.contains("keep_generations = 10"),
        "{}",
        toml.stdout
    );
    fx.laft(&["eval", "nothing.here"]).expect(11);

    let options = fx.laft(&["options", "gc."]).expect(0);
    assert!(
        options.stdout.contains("gc.keep_days"),
        "{}",
        options.stdout
    );
    let explain = fx.laft(&["explain", "S001"]).expect(0);
    assert!(explain.stdout.starts_with("S001: "), "{}", explain.stdout);
    fx.laft(&["explain", "X1"]).expect(2);

    let part = fx.dir().join("part.stav");
    std::fs::write(&part, "system { packages = [anything] }\n").expect("writable");
    fx.laft(&["check", part.to_str().expect("UTF-8")]).expect(0);
    std::fs::write(&part, "system { hostname = 1 }\n").expect("writable");
    fx.laft(&["check", part.to_str().expect("UTF-8")])
        .expect(11);
}

#[test]
fn formatting_standard_input_with_check_prints_nothing_and_fails_on_a_change() {
    use std::io::Write;
    use std::process::{Command, Stdio};
    let check = |text: &str| {
        let mut child = Command::new(env!("CARGO_BIN_EXE_laft"))
            .args(["fmt", "--stdin", "--check"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .spawn()
            .expect("laft runs");
        child
            .stdin
            .take()
            .expect("piped")
            .write_all(text.as_bytes())
            .expect("writable");
        child.wait_with_output().expect("finishes")
    };
    let ugly = check("system {\nhostname = \"a\"\n}\n");
    assert_eq!(ugly.status.code(), Some(1));
    assert!(ugly.stdout.is_empty());
    let tidy = check("system {\n  hostname = \"a\"\n}\n");
    assert_eq!(tidy.status.code(), Some(0));
}

#[test]
fn verify_links_checks_the_views_of_a_generation() {
    let fx = fixture!(pkg("hello", "1.0").file("usr/bin/hello", b"#!/bin/sh\necho hello\n"));
    fx.configure("", "  view dev { packages = [hello] }");
    fx.laft(&["apply", "-y"]).expect(0);
    fx.laft(&["verify", "--links"]).expect(0);
    let copy = fx.root().join("laft/views/dev/1/usr/bin/hello");
    let mode = std::fs::metadata(&copy).expect("in the view").permissions();
    let parent = copy.parent().expect("a directory").to_path_buf();
    let writable = |on: bool| {
        use std::os::unix::fs::PermissionsExt;
        let mode = if on { 0o755 } else { 0o555 };
        std::fs::set_permissions(&parent, std::fs::Permissions::from_mode(mode)).expect("chmod");
    };
    writable(true);
    std::fs::remove_file(&copy).expect("removable");
    std::fs::write(&copy, "#!/bin/sh\necho hello\n").expect("writable");
    std::fs::set_permissions(&copy, mode).expect("chmod");
    writable(false);
    let report = fx.laft(&["verify", "--links"]);
    assert_ne!(report.code, 0, "{}", report.stdout);
    assert!(report.stdout.contains("view dev"), "{}", report.stdout);
}
